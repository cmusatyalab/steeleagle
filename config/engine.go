package config

import "fmt"

// ForwardsAll is the engine cap forwards value meaning the engine forwards
// all of its input types.
const ForwardsAll = "*"

type EngineCap struct {
	// Type of engine (one of "detection", "classification", "guidance", "position"
	// "generic", "filter")
	Type string `toml:"type"`
	// Input types supported by this engine
	Inputs []string `toml:"inputs"`
	// Type this engine sends on along its output edges (optional, defaults
	// to "*"): "*" passes on each input as it is, one of its input types
	// passes on only that type, and any other type means the engine converts
	// each input it takes into that type (an encoder or a decoder)
	Forwards string `toml:"forwards,omitempty"`
	// Result type generated by this engine
	Result string `toml:"result,omitempty"`
	// Producers advertised by this engine (optional)
	Producers []EngineProducer `toml:"producers,omitempty"`
}

type EngineProducer struct {
	// Producer name, advertised as STEELEAGLE_ENGINE_ENDPOINT.<name>
	Name string `toml:"name"`
	// Output type of the producer
	Output string `toml:"output"`
}

// validate defaults forwards to all input types and checks the engine's
// producers.
func (e *EngineCap) validate() error {
	if e.Forwards == "" {
		e.Forwards = ForwardsAll
	}
	names := make(map[string]struct{}, len(e.Producers))
	for _, p := range e.Producers {
		if p.Name == "" {
			return fmt.Errorf("engine cap has a producer with no name")
		}
		if _, ok := names[p.Name]; ok {
			return fmt.Errorf("engine cap producer %q is declared more than once", p.Name)
		}
		names[p.Name] = struct{}{}
		if p.Output == "" {
			return fmt.Errorf("engine cap producer %q has no output type", p.Name)
		}
	}
	return nil
}

// GetProducer returns the config of the engine's producer called name, or an
// error if the engine has no such producer.
func (e *EngineCap) GetProducer(name string) (EngineProducer, error) {
	for _, p := range e.Producers {
		if p.Name == name {
			return p, nil
		}
	}
	return EngineProducer{}, fmt.Errorf("engine has no producer %q", name)
}

// MatchesInputType checks whether an engine accepts the given input type.
func (e *EngineCap) MatchesInputType(inputType string) bool {
	for _, i := range e.Inputs {
		if i == inputType {
			return true
		}
	}
	return false
}

// MatchesForwardedType checks whether an engine forwards the given input type
// unchanged. An empty forwards value is treated as "*"; an engine that
// converts its inputs forwards none of them.
func (e *EngineCap) MatchesForwardedType(inputType string) bool {
	if e.Forwards == "" || e.Forwards == ForwardsAll {
		return e.MatchesInputType(inputType)
	}
	return e.Forwards == inputType && e.MatchesInputType(inputType)
}

// Converts checks whether an engine converts each input it takes into its
// forwards type, which is not one of its input types.
func (e *EngineCap) Converts() bool {
	return e.Forwards != "" && e.Forwards != ForwardsAll && !e.MatchesInputType(e.Forwards)
}

// MatchesResultType checks whether an engine generates the given result type.
func (e *EngineCap) MatchesResultType(resultType string) bool {
	return e.Result == resultType
}
