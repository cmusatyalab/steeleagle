#!/usr/bin/env bash
#
# basicsim.sh - generate and load a FireQOS config that caps bandwidth
# for traffic on a given port of a given interface.
#
# Usage:
#   sudo ./basicsim.sh start -i <iface> -p <port> -b <bw> [-d in|out] [-l <link-rate>] [-c <config>]
#   sudo ./basicsim.sh start -i <iface> -p <port> -k [-d in|out]
#   sudo ./basicsim.sh stop
#   sudo ./basicsim.sh status [-i <iface>]
#
# Examples:
#   sudo ./basicsim.sh start -i eth0 -p 5201 -b 10Mbit
#   sudo ./basicsim.sh start -i ens3 -p 443 -b 500kbit -d out -l 1Gbit
#   sudo ./basicsim.sh start -i eth0 -p 5201 -k
#
# Bandwidth values use FireQOS/tc units: kbit, Mbit, Gbit (bits) or kbps, Mbps (bytes).
# -k (kill) drops all TCP/UDP traffic on the port with iptables instead of shaping.
# It stays in the foreground; the block is removed on Ctrl-C/termination or by 'stop'.

set -euo pipefail

IFACE=""
PORT=""
BW=""
DIRECTION="both"
LINK_RATE="10Gbit"
CONFIG="/etc/firehol/netsim.conf"
KILL=0
KILL_CHAIN_IN="NETSIM_KILL_IN"
KILL_CHAIN_OUT="NETSIM_KILL_OUT"

usage() {
    sed -n '3,19p' "$0" | sed 's/^# \{0,1\}//'
    exit "${1:-1}"
}

die() {
    echo "error: $*" >&2
    exit 1
}

parse_args() {
    while getopts ":i:p:b:d:l:c:kh" opt; do
        case "$opt" in
            i) IFACE="$OPTARG" ;;
            p) PORT="$OPTARG" ;;
            b) BW="$OPTARG" ;;
            d)
                [[ "$OPTARG" == in || "$OPTARG" == out ]] \
                    || die "direction (-d) must be in or out (omit for both)"
                DIRECTION="$OPTARG"
                ;;
            l) LINK_RATE="$OPTARG" ;;
            c) CONFIG="$OPTARG" ;;
            k) KILL=1 ;;
            h) usage 0 ;;
            :) die "option -$OPTARG requires an argument" ;;
            *) die "unknown option -$OPTARG" ;;
        esac
    done
}

validate() {
    [[ -n "$IFACE" ]] || die "interface (-i) is required"
    [[ -n "$PORT" ]] || die "port (-p) is required"
    ip link show "$IFACE" &>/dev/null || die "interface '$IFACE' does not exist"
    [[ "$PORT" =~ ^[0-9]+$ ]] && (( PORT >= 1 && PORT <= 65535 )) \
        || die "port must be an integer in 1-65535"

    if (( KILL )); then
        [[ -z "$BW" ]] || die "-k blocks the port entirely; do not combine it with -b"
        return
    fi
    [[ -n "$BW" ]] || die "bandwidth (-b) is required (or -k to block the port)"

    local rate_re='^[0-9]+(\.[0-9]+)?([kKmMgG]?(bit|bps))$'
    [[ "$BW" =~ $rate_re ]] || die "bandwidth '$BW' must look like 10Mbit, 500kbit, 1Gbit, 2Mbps"
    [[ "$LINK_RATE" =~ $rate_re ]] || die "link rate '$LINK_RATE' must look like 1Gbit, 100Mbit"

    # HTB cannot shape to zero; blocking a port is a firewall job.
    [[ "${BW%%[!0-9.]*}" =~ [1-9] ]] \
        || die "bandwidth must be > 0; to block port $PORT use -k"
}

# Emit one FireQOS interface block. Traffic on $PORT (src or dst) goes to a
# class pinned at $BW; everything else falls into the default class and can
# use the full link rate.
emit_interface() {
    local dir="$1" name="$2"
    cat <<EOF
interface $IFACE $name $dir rate $LINK_RATE
    class port$PORT commit $BW ceil $BW
        match port $PORT
EOF
}

write_config() {
    mkdir -p "$(dirname "$CONFIG")"
    {
        echo "# Generated by $(basename "$0") on $(date -Is)"
        echo "# Limit port $PORT on $IFACE to $BW ($DIRECTION)"
        echo
        if [[ "$DIRECTION" == "out" || "$DIRECTION" == "both" ]]; then
            emit_interface output "${IFACE}-out"
            echo
        fi
        if [[ "$DIRECTION" == "in" || "$DIRECTION" == "both" ]]; then
            emit_interface input "${IFACE}-in"
        fi
    } > "$CONFIG"
    echo "Wrote $CONFIG:"
    sed 's/^/  /' "$CONFIG"
}

require_root() {
    (( EUID == 0 )) || die "must be run as root (try sudo)"
}

# iptables, plus ip6tables when present, so IPv6 traffic is blocked too.
ipt_cmds() {
    command -v iptables &>/dev/null || die "iptables not found"
    echo iptables
    if command -v ip6tables &>/dev/null; then echo ip6tables; fi
}

kill_active() {
    iptables -n -L "$KILL_CHAIN_IN" &>/dev/null || iptables -n -L "$KILL_CHAIN_OUT" &>/dev/null
}

# Each direction gets its own chain (-i is invalid on OUTPUT, -o on INPUT),
# hooked in at the top of INPUT/OUTPUT so existing connections are cut too.
kill_add_chain() {
    local ipt="$1" chain="$2" parent="$3" ifflag="$4" proto flag
    "$ipt" -N "$chain"
    for proto in tcp udp; do
        for flag in --dport --sport; do
            "$ipt" -A "$chain" "$ifflag" "$IFACE" -p "$proto" "$flag" "$PORT" -j DROP
        done
    done
    "$ipt" -I "$parent" 1 -j "$chain"
}

kill_start() {
    local ipt
    for ipt in $(ipt_cmds); do
        if [[ "$DIRECTION" == "in" || "$DIRECTION" == "both" ]]; then
            kill_add_chain "$ipt" "$KILL_CHAIN_IN" INPUT -i
        fi
        if [[ "$DIRECTION" == "out" || "$DIRECTION" == "both" ]]; then
            kill_add_chain "$ipt" "$KILL_CHAIN_OUT" OUTPUT -o
        fi
    done
}

# Idempotent: safe to call when nothing (or only part) was installed.
kill_stop() {
    local ipt chain parent
    for ipt in $(ipt_cmds); do
        for chain in "$KILL_CHAIN_IN" "$KILL_CHAIN_OUT"; do
            "$ipt" -n -L "$chain" &>/dev/null || continue
            [[ "$chain" == "$KILL_CHAIN_IN" ]] && parent=INPUT || parent=OUTPUT
            while "$ipt" -D "$parent" -j "$chain" 2>/dev/null; do :; done
            "$ipt" -F "$chain"
            "$ipt" -X "$chain"
        done
    done
}

kill_cleanup() {
    trap - EXIT INT TERM HUP
    kill_stop
    echo "Unblocked port $PORT on $IFACE"
}

# Block the port, then wait until interrupted or until 'stop' removes the chains.
run_kill() {
    kill_active && die "a port block is already active; run 'stop' first"
    trap kill_cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP
    kill_start
    echo "Blocking TCP/UDP port $PORT on $IFACE ($DIRECTION). Ctrl-C or '$(basename "$0") stop' to unblock."
    while kill_active; do sleep 1; done
}

require_fireqos() {
    command -v fireqos &>/dev/null \
        || die "fireqos not found; install it (e.g. 'apt install firehol' or 'apt install fireqos')"
}

cmd="${1:-}"
[[ -n "$cmd" ]] || usage
shift

case "$cmd" in
    start)
        parse_args "$@"
        validate
        require_root
        if (( KILL )); then
            run_kill
            exit 0
        fi
        require_fireqos
        write_config
        fireqos start "$CONFIG"
        ;;
    stop)
        require_root
        kill_stop
        if command -v fireqos &>/dev/null; then
            fireqos stop
        fi
        ;;
    status)
        parse_args "$@"
        require_fireqos
        if [[ -n "$IFACE" ]]; then
            fireqos status "${IFACE}-out"
        else
            tc -s qdisc show
        fi
        ;;
    -h|--help|help)
        usage 0
        ;;
    *)
        usage
        ;;
esac
