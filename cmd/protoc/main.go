package main

import (
	"fmt"
	"path"
	"slices"
	"strings"
	"unicode"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

		// Group files by import rather than individual files to prevent name collisions
		groups := map[protogen.GoImportPath][]*protogen.File{}
		var order []protogen.GoImportPath
		for _, f := range gen.Files {
			if !f.Generate || !slices.Contains(wantedPackages, string(f.Desc.Package())) {
				continue
			}
			if _, ok := groups[f.GoImportPath]; !ok {
				order = append(order, f.GoImportPath)
			}
			groups[f.GoImportPath] = append(groups[f.GoImportPath], f)
		}

		for _, importPath := range order {
			generatePackage(gen, importPath, groups[importPath])
		}
		return nil
	})
}

// generatePackage creates exactly one wrapper interface file and one
// wrapper message file per Go package (import path).
func generatePackage(gen *protogen.Plugin, importPath protogen.GoImportPath, files []*protogen.File) {
	sdkImportPath := protogen.GoImportPath("github.com/cmusatyalab/steeleagle/sdk/types")
	base := packageFileBase(importPath)

	gIFace := gen.NewGeneratedFile(base+"_iface.pb.go", sdkImportPath)
	gIFace.P("// Code generated by protoc interface plugin. DO NOT EDIT.")
	gIFace.P()
	gIFace.P("package types")
	gIFace.P()

	gMsg := gen.NewGeneratedFile(base+"_msg.pb.go", sdkImportPath)
	gMsg.P("// Code generated by protoc interface plugin. DO NOT EDIT.")
	gMsg.P()
	gMsg.P("package types")
	gMsg.P()

	for _, file := range files {
		// Top-level (file-scoped) enums — declared before any interface
		// that references them, though Go doesn't actually require this
		// ordering.
		for _, enum := range file.Enums {
			generateEnum(gIFace, enum)
		}

		for _, msg := range file.Messages {
			// Only generate message if it is not hidden (like RawFrame)
			if !isHiddenMessage(string(msg.Desc.FullName())) {
				generateEnumsRecursive(gIFace, msg)
				generateIFace(gIFace, msg)
				generateMessage(gMsg, msg)
			}
		}
	}
}

// packageFileBase derives a collision-safe output filename from a Go
// import path, e.g. ".../services/driver/control" becomes
// "_services_driver_control".
func packageFileBase(importPath protogen.GoImportPath) string {
	return strings.NewReplacer("/", "_", ".", "_", "-", "_").Replace(string(importPath))
}

// isHiddenMessage reports whether a message's fully-qualified proto name
// is not wanted.
func isHiddenMessage(fullName string) bool {
	for _, pattern := range hiddenMessages {
		matched, err := path.Match(pattern, fullName)
		if err != nil {
			panic(fmt.Sprintf("invalid hiddenMessages glob pattern %q: %v", pattern, err))
		}
		if matched {
			return true
		}
	}
	return false
}

// generateEnum defines a Go-native adapter enum type that mirrors a protobuf enum's
// values, entirely decoupled from the real protoc-gen-go-generated enum type.
func generateEnum(g *protogen.GeneratedFile, enum *protogen.Enum) {
	typeName := enum.GoIdent.GoName
	g.P("type ", typeName, " int32")
	g.P()
	g.P("const (")
	for _, v := range enum.Values {
		g.P(enumValueConstName(enum, v), " ", typeName, " = ", v.Desc.Number())
	}
	g.P(")")
	g.P()
}

// enumValueConstName computes a stripped, idiomatic Go constant name for an
// enum value.
func enumValueConstName(enum *protogen.Enum, v *protogen.EnumValue) string {
	localPrefix := screamingSnake(string(enum.Desc.Name())) + "_"
	valName := string(v.Desc.Name())
	if !strings.HasPrefix(valName, localPrefix) {
		return v.GoIdent.GoName // safe fallback — always correct, just not stripped
	}
	suffix := strings.TrimPrefix(valName, localPrefix)
	if suffix == "" {
		return v.GoIdent.GoName // whole name equaled the prefix — nothing to append
	}
	return enum.GoIdent.GoName + camelCaseSnake(suffix)
}

// generateEnumsRecursive emits masked enum types for every enum nested (at
// any depth) inside msg — proto allows enums nested inside nested messages,
// not just directly inside a top-level message.
func generateEnumsRecursive(g *protogen.GeneratedFile, msg *protogen.Message) {
	for _, enum := range msg.Enums {
		generateEnum(g, enum)
	}
	for _, nested := range msg.Messages {
		generateEnumsRecursive(g, nested)
	}
}

// generateIFace defines a new protobuf type interface. These will be
// overlaid during compilation if a vehicle does not satisfy the full
// capability set.
func generateIFace(g *protogen.GeneratedFile, msg *protogen.Message) {
	ifaceName := msg.GoIdent.GoName
	g.P("type ", ifaceName, " interface {")
	for _, field := range msg.Fields {
		emitInterfaceMethod(g, field)
	}
	g.P("}")
	g.P()
}

// generateMessage defines a new protobuf message wrapper.
func generateMessage(g *protogen.GeneratedFile, msg *protogen.Message) {
	wrapperName := unexportedName(msg.GoIdent.GoName) + "Wrapper"
	g.P("type ", wrapperName, " struct {")
	g.P("inner *", msg.GoIdent, " // generated concrete type")
	g.P("}")
	g.P()

	for _, field := range msg.Fields {
		emitAdapterMethod(g, wrapperName, field)
	}

	for _, nested := range msg.Messages {
		generateMessage(g, nested)
	}
}

// emitInterfaceMethod replicates the opaque protobuf API for a given
// message field.
func emitInterfaceMethod(g *protogen.GeneratedFile, field *protogen.Field) {
	getterName := "Get" + field.GoName
	optional := isOptional(field)

	switch {
	case field.Desc.IsList() && field.Message != nil && !isWellKnownType(field):
		g.P(getterName, "() []", field.Message.GoIdent.GoName)

	case field.Desc.IsList() && field.Message != nil && isWellKnownType(field):
		typ, _ := wellKnownType(g, field)
		g.P(getterName, "() []", typ)

	case field.Message != nil && !isWellKnownType(field):
		emitGetterSignature(g, getterName, field.Message.GoIdent.GoName, optional)

	default:
		returnType := fieldReturnType(g, field)
		emitGetterSignature(g, getterName, returnType, optional)
	}

	if optional {
		g.P("has", field.GoName, "() bool")
	}

	emitSetterSignature(g, field)
}

// emitSetterSignature writes the Set<Field>(v Type) interface method for a
// singular field. Repeated/map fields are skipped, since they are modified
// with a mutable Get.
func emitSetterSignature(g *protogen.GeneratedFile, field *protogen.Field) {
	if field.Desc.IsList() || field.Desc.IsMap() {
		return
	}
	setterName := "Set" + field.GoName
	switch {
	case field.Message != nil && !isWellKnownType(field):
		g.P(setterName, "(v ", field.Message.GoIdent.GoName, ")")
	default:
		g.P(setterName, "(v ", fieldReturnType(g, field), ")")
	}
}

// emitGetterSignature writes a single interface method signature, either
// "Name() Type" or "Name() (Type, error)" depending on optional.
func emitGetterSignature(g *protogen.GeneratedFile, getterName, typ string, optional bool) {
	if optional {
		g.P(getterName, "() (", typ, ", error)")
	} else {
		g.P(getterName, "() ", typ)
	}
}

// emitAdapterMethod creates adapters that plug in to the protocol with
// opaque interfaces.
func emitAdapterMethod(g *protogen.GeneratedFile, wrapperName string, field *protogen.Field) {
	getterName := "Get" + field.GoName
	recv := "w"
	optional := isOptional(field)

	switch {
	case field.Desc.IsList() && field.Message != nil && !isWellKnownType(field):
		elemWrapper := unexportedName(field.Message.GoIdent.GoName) + "Wrapper"
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() []", field.Message.GoIdent.GoName, " {")
		g.P("src := ", recv, ".inner.", getterName, "()")
		g.P("out := make([]", field.Message.GoIdent.GoName, ", len(src))")
		g.P("for i, v := range src {")
		g.P("out[i] = &", elemWrapper, "{inner: v}")
		g.P("}")
		g.P("return out")
		g.P("}")

	case field.Desc.IsList() && field.Message != nil && isWellKnownType(field):
		typ, _ := wellKnownType(g, field)
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() []", typ, " {")
		g.P("return ", recv, ".inner.", getterName, "()")
		g.P("}")

	case field.Message != nil && !isWellKnownType(field):
		nestedWrapper := unexportedName(field.Message.GoIdent.GoName) + "Wrapper"
		ifaceType := field.Message.GoIdent.GoName
		emitMessageGetterBody(g, recv, wrapperName, getterName, field, ifaceType, nestedWrapper, optional)

	default:
		returnType := fieldReturnType(g, field)
		emitScalarGetterBody(g, recv, wrapperName, getterName, field, returnType, optional)
	}
	g.P()

	if optional {
		g.P("func (", recv, " *", wrapperName, ") has", field.GoName, "() bool {")
		g.P("return ", recv, ".inner.Has", field.GoName, "()")
		g.P("}")
		g.P()
	}

	emitSetterAdapter(g, recv, wrapperName, field)
}

// emitSetterAdapter writes the Set<Field>(v Type) wrapper method body for a
// singular field (repeated/map fields are skipped, matching
// emitSetterSignature).
func emitSetterAdapter(g *protogen.GeneratedFile, recv, wrapperName string, field *protogen.Field) {
	if field.Desc.IsList() || field.Desc.IsMap() {
		return
	}
	setterName := "Set" + field.GoName

	switch {
	case field.Message != nil && !isWellKnownType(field):
		nestedWrapper := unexportedName(field.Message.GoIdent.GoName) + "Wrapper"
		ifaceType := field.Message.GoIdent.GoName
		g.P("func (", recv, " *", wrapperName, ") ", setterName, "(v ", ifaceType, ") {")
		g.P("if v == nil {")
		g.P(recv, ".inner.", setterName, "(nil)")
		g.P("return")
		g.P("}")
		g.P(recv, ".inner.", setterName, "(v.(*", nestedWrapper, ").inner)")
		g.P("}")
		g.P()

	case field.Enum != nil:
		protoEnumType := g.QualifiedGoIdent(field.Enum.GoIdent) // real protobuf enum type — needed only here, for the cast
		g.P("func (", recv, " *", wrapperName, ") ", setterName, "(v ", field.Enum.GoIdent.GoName, ") {")
		g.P(recv, ".inner.", setterName, "(", protoEnumType, "(v))")
		g.P("}")
		g.P()

	default:
		returnType := fieldReturnType(g, field)
		g.P("func (", recv, " *", wrapperName, ") ", setterName, "(v ", returnType, ") {")
		g.P(recv, ".inner.", setterName, "(v)")
		g.P("}")
		g.P()
	}
}

// emitMessageGetterBody writes the Get<Field>() body for a nested-message
// field, wrapping the concrete value in its adapter type.
func emitMessageGetterBody(g *protogen.GeneratedFile, recv, wrapperName, getterName string, field *protogen.Field, ifaceType, nestedWrapper string, optional bool) {
	if optional {
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() (", ifaceType, ", error) {")
		g.P("if !", recv, ".has", field.GoName, "() {")
		g.P("return nil, ", fmtErrorf(g), "(\"field not present in message, using default value\")")
		g.P("}")
		g.P("return &", nestedWrapper, "{inner: ", recv, ".inner.", getterName, "()}, nil")
		g.P("}")
		return
	}
	g.P("func (", recv, " *", wrapperName, ") ", getterName, "() ", ifaceType, " {")
	g.P("return &", nestedWrapper, "{inner: ", recv, ".inner.", getterName, "()}")
	g.P("}")
}

// emitScalarGetterBody writes the Get<Field>() body for a scalar, enum, or
// well-known-type field that converts from the adapter type to the true type.
func emitScalarGetterBody(g *protogen.GeneratedFile, recv, wrapperName, getterName string, field *protogen.Field, returnType string, optional bool) {
	readExpr := recv + ".inner." + getterName + "()"
	if field.Enum != nil {
		readExpr = returnType + "(" + readExpr + ")"
	}

	if optional {
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() (", returnType, ", error) {")
		g.P("if !", recv, ".has", field.GoName, "() {")
		g.P("var zero ", returnType)
		g.P("return zero, ", fmtErrorf(g), "(\"field not present in message, using default value\")")
		g.P("}")
		g.P("return ", readExpr, ", nil")
		g.P("}")
		return
	}
	g.P("func (", recv, " *", wrapperName, ") ", getterName, "() ", returnType, " {")
	g.P("return ", readExpr)
	g.P("}")
}

// isOptional reports whether protoc-gen-go generates a Has<Field>() method.
func isOptional(field *protogen.Field) bool {
	if field.Desc.IsList() || field.Desc.IsMap() {
		return false // repeated/map fields never get Has*
	}
	if field.Message != nil {
		return true // singular message fields always have Has*, no optional keyword needed
	}
	return field.Desc.HasOptionalKeyword()
}

// fmtErrorfIdent manually constructs an error when a field doesn't exist.
var fmtErrorfIdent = protogen.GoIdent{GoName: "Errorf", GoImportPath: "fmt"}

func fmtErrorf(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(fmtErrorfIdent)
}

// unexportedName converts an exported name to an unexported name by
// lowercasing the first character.
func unexportedName(name string) string {
	if name == "" {
		return name
	}
	r := []rune(name)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}
