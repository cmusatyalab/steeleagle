package main

import (
	"slices"
	"strings"
	"unicode"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range gen.FilesByPath {
			if !f.Generate || !slices.Contains(wantedPackages, string(f.Desc.Package())) {
				continue
			}
			generateFile(gen, f)
		}
		return nil
	})
}

// generateFile creates a new generated protobuf wrapper file that wraps
// over the SteelEagle API. These wrappers are primarily used for compile
// time checking of runtime capabilities.
func generateFile(gen *protogen.Plugin, file *protogen.File) {
	sdkImportPath := protogen.GoImportPath("github.com/cmusatyalab/steeleagle/sdk/types")
	pkg := strings.ReplaceAll(string(file.Desc.Package()), ".", "_")

	gIFace := gen.NewGeneratedFile(pkg+"_iface.pb.go", sdkImportPath)
	gIFace.P("// Code generated by protoc interface plugin. DO NOT EDIT.")
	gIFace.P()
	gIFace.P("package types")
	gIFace.P()

	gMsg := gen.NewGeneratedFile(pkg+"_msg.pb.go", sdkImportPath)
	gMsg.P("// Code generated by protoc interface plugin. DO NOT EDIT.")
	gMsg.P()
	gMsg.P("package types")
	gMsg.P()

	for _, msg := range file.Messages {
		// Only generate message if it is not hidden (like RawFrame)
		if !slices.Contains(hiddenMessages, string(msg.Desc.FullName())) {
			generateIFace(gIFace, msg)
			generateMessage(gMsg, msg)
		}
	}
}

// generateIFace defines a new protobuf type interface. These will be
// overlaid during compilation if a vehicle does not satisfy the full
// capability set.
func generateIFace(g *protogen.GeneratedFile, msg *protogen.Message) {
	ifaceName := msg.GoIdent.GoName
	g.P("type ", ifaceName, " interface {")
	for _, field := range msg.Fields {
		emitInterfaceMethod(g, field)
	}
	g.P("}")
	g.P()
}

// generateMessage defines a new protobuf message wrapper.
func generateMessage(g *protogen.GeneratedFile, msg *protogen.Message) {
	wrapperName := unexportedName(msg.GoIdent.GoName) + "Wrapper"
	g.P("type ", wrapperName, " struct {")
	g.P("inner *", msg.GoIdent, " // generated concrete type")
	g.P("}")
	g.P()

	for _, field := range msg.Fields {
		emitAdapterMethod(g, wrapperName, field)
	}

	for _, nested := range msg.Messages {
		generateMessage(g, nested)
	}
}

// emitInterfaceMethod replicates the opaque protobuf API for a given
// message field. Optional fields return (Type, error) for Getters,
// while non-optional fields return Type.
func emitInterfaceMethod(g *protogen.GeneratedFile, field *protogen.Field) {
	getterName := "Get" + field.GoName
	optional := isOptional(field)

	switch {
	case field.Desc.IsList() && field.Message != nil && !isWellKnownType(field):
		g.P(getterName, "() []", field.Message.GoIdent.GoName)

	case field.Desc.IsList() && field.Message != nil && isWellKnownType(field):
		typ, _ := wellKnownType(g, field)
		g.P(getterName, "() []", typ)

	case field.Message != nil && !isWellKnownType(field):
		emitGetterSignature(g, getterName, field.Message.GoIdent.GoName, optional)

	default:
		returnType := fieldReturnType(g, field)
		emitGetterSignature(g, getterName, returnType, optional)
	}

	if optional {
		g.P("has", field.GoName, "() bool")
	}
}

// emitGetterSignature writes a single interface method signature, either
// "Name() Type" or "Name() (Type, error)" depending on optional.
func emitGetterSignature(g *protogen.GeneratedFile, getterName, typ string, optional bool) {
	if optional {
		g.P(getterName, "() (", typ, ", error)")
	} else {
		g.P(getterName, "() ", typ)
	}
}

// emitAdapterMethod creates adapters that plug in to the protocol with
// opaque interfaces.
func emitAdapterMethod(g *protogen.GeneratedFile, wrapperName string, field *protogen.Field) {
	getterName := "Get" + field.GoName
	recv := "w"
	optional := isOptional(field)

	switch {
	case field.Desc.IsList() && field.Message != nil && !isWellKnownType(field):
		elemWrapper := unexportedName(field.Message.GoIdent.GoName) + "Wrapper"
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() []", field.Message.GoIdent.GoName, " {")
		g.P("src := ", recv, ".inner.", getterName, "()")
		g.P("out := make([]", field.Message.GoIdent.GoName, ", len(src))")
		g.P("for i, v := range src {")
		g.P("out[i] = &", elemWrapper, "{inner: v}")
		g.P("}")
		g.P("return out")
		g.P("}")

	case field.Desc.IsList() && field.Message != nil && isWellKnownType(field):
		typ, _ := wellKnownType(g, field)
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() []", typ, " {")
		g.P("return ", recv, ".inner.", getterName, "()")
		g.P("}")

	case field.Message != nil && !isWellKnownType(field):
		nestedWrapper := unexportedName(field.Message.GoIdent.GoName) + "Wrapper"
		ifaceType := field.Message.GoIdent.GoName
		emitMessageGetterBody(g, recv, wrapperName, getterName, field, ifaceType, nestedWrapper, optional)

	default:
		returnType := fieldReturnType(g, field)
		emitScalarGetterBody(g, recv, wrapperName, getterName, field, returnType, optional)
	}
	g.P()

	if optional {
		g.P("func (", recv, " *", wrapperName, ") has", field.GoName, "() bool {")
		g.P("return ", recv, ".inner.Has", field.GoName, "()")
		g.P("}")
		g.P()
	}
}

// emitMessageGetterBody writes the Get<Field>() body for a nested-message
// field, wrapping the concrete value in its adapter type.
func emitMessageGetterBody(g *protogen.GeneratedFile, recv, wrapperName, getterName string, field *protogen.Field, ifaceType, nestedWrapper string, optional bool) {
	if optional {
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() (", ifaceType, ", error) {")
		g.P("if !", recv, ".has", field.GoName, "() {")
		g.P("return nil, ", fmtErrorf(g), "(\"field not present in message, using default value\")")
		g.P("}")
		g.P("return &", nestedWrapper, "{inner: ", recv, ".inner.", getterName, "()}, nil")
		g.P("}")
		return
	}
	g.P("func (", recv, " *", wrapperName, ") ", getterName, "() ", ifaceType, " {")
	g.P("return &", nestedWrapper, "{inner: ", recv, ".inner.", getterName, "()}")
	g.P("}")
}

// emitScalarGetterBody writes the Get<Field>() body for a scalar, enum, or
// well-known-type field.
func emitScalarGetterBody(g *protogen.GeneratedFile, recv, wrapperName, getterName string, field *protogen.Field, returnType string, optional bool) {
	if optional {
		g.P("func (", recv, " *", wrapperName, ") ", getterName, "() (", returnType, ", error) {")
		g.P("if !", recv, ".has", field.GoName, "() {")
		g.P("var zero ", returnType)
		g.P("return zero, ", fmtErrorf(g), "(\"field not present in message, using default value\")")
		g.P("}")
		g.P("return ", recv, ".inner.", getterName, "(), nil")
		g.P("}")
		return
	}
	g.P("func (", recv, " *", wrapperName, ") ", getterName, "() ", returnType, " {")
	g.P("return ", recv, ".inner.", getterName, "()")
	g.P("}")
}

// isOptional reports whether protoc-gen-go generates a Has<Field>() method.
func isOptional(field *protogen.Field) bool {
	if field.Desc.IsList() || field.Desc.IsMap() {
		return false // repeated/map fields never get Has* — presence is len() == 0
	}
	if field.Message != nil {
		return true // singular message fields always have Has*, no optional keyword needed
	}
	return field.Desc.HasOptionalKeyword()
}

// fmtErrorfIdent manually constructs the error message for a Getter.
var fmtErrorfIdent = protogen.GoIdent{GoName: "Errorf", GoImportPath: "fmt"}

func fmtErrorf(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(fmtErrorfIdent)
}

// unexportedName converts an exported name to an unexported name by
// lowercasing the first character.
func unexportedName(name string) string {
	if name == "" {
		return name
	}
	r := []rune(name)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}
