package main

import (
	"fmt"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	"github.com/cmusatyalab/steeleagle/sdk/preprocess"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

		groups := map[protogen.GoImportPath][]*protogen.File{}
		var order []protogen.GoImportPath
		for _, f := range gen.Files {
			if !f.Generate || !slices.Contains(wantedPackages, string(f.Desc.Package())) {
				continue
			}
			if _, ok := groups[f.GoImportPath]; !ok {
				order = append(order, f.GoImportPath)
			}
			groups[f.GoImportPath] = append(groups[f.GoImportPath], f)
		}

		generatePackages(gen, order, groups)
		return nil
	})
}

// generatePackages builds all the protobuf files into the core generated files.
func generatePackages(gen *protogen.Plugin, importPaths []protogen.GoImportPath, groups map[protogen.GoImportPath][]*protogen.File) {
	gIface := gen.NewGeneratedFile("interface.pb.go", sdkImportPath)
	gIface.P("// Code generated by SteelEagle protoc plugin. DO NOT EDIT.")
	gIface.P()
	gIface.P("package sdk")
	gIface.P()
	gMsg := gen.NewGeneratedFile("message.pb.go", sdkImportPath)
	gMsg.P("// Code generated by SteelEagle protoc interface plugin. DO NOT EDIT.")
	gMsg.P()
	gMsg.P("package sdk")
	gMsg.P()
	gTypes := gen.NewGeneratedFile(filepath.Join("enums", "enums.pb.go"), enumsImportPath)
	gTypes.P("// Code generated by SteelEagle protoc interface plugin. DO NOT EDIT.")
	gTypes.P()
	gTypes.P("package enums")
	gTypes.P()

	for _, path := range importPaths {
		for _, file := range groups[path] {
			filePrefix := capFilePrefix(file)
			for _, enum := range file.Enums {
				generateEnum(gTypes, enum, filePrefix)
			}
			for _, msg := range file.Messages {
				if !isHiddenMessage(string(msg.Desc.FullName())) {
					generateEnumsRecursive(gTypes, msg, filePrefix)
					if !isCommonMessage(msg) {
						generateIface(gIface, msg, filePrefix+"/"+msg.GoIdent.GoName)
					}
					generateMessage(gMsg, msg)
				}
			}
		}
	}
}

// generateEnumsRecursive emits masked enum types for every enum nested (at
// any depth) inside msg. filePrefix is msg's file's capability path
// prefix (see capFilePrefix).
func generateEnumsRecursive(g *protogen.GeneratedFile, msg *protogen.Message, filePrefix string) {
	for _, enum := range msg.Enums {
		generateEnum(g, enum, filePrefix)
	}
	for _, nested := range msg.Messages {
		generateEnumsRecursive(g, nested, filePrefix)
	}
}

// generateIface defines a new protobuf type interface. These will be
// overlaid during compilation if a vehicle does not satisfy the full
// capability set. msgPath is msg's own capability path (see
// capFilePrefix) - e.g. "services/control/TakeOffRequest".
func generateIface(g *protogen.GeneratedFile, msg *protogen.Message, msgPath string) {
	parentGoName := msg.GoIdent.GoName

	for _, field := range msg.Fields {
		if needsCommonFieldInterface(field) {
			fieldPath := msgPath + "/" + string(field.Desc.Name())
			emitCommonFieldInterface(g, parentGoName, fieldPath, field)
		}
	}

	g.P("type ", parentGoName, " interface {")
	for _, field := range msg.Fields {
		fieldPath := msgPath + "/" + string(field.Desc.Name())
		emitInterfaceMethod(g, parentGoName, fieldPath, field)
	}
	g.P("}")
	g.P()
}

// generateMessage defines a new protobuf message wrapper. wrapperName
// comes from messageWrapperName.
func generateMessage(g *protogen.GeneratedFile, msg *protogen.Message) {
	parentGoName := msg.GoIdent.GoName
	wrapperName := messageWrapperName(msg)
	g.P("type ", wrapperName, " struct {")
	g.P("inner *", msg.GoIdent, " // generated concrete type")
	g.P("}")
	g.P()

	for _, field := range msg.Fields {
		emitAdapterMethod(g, parentGoName, wrapperName, field)
	}

	for _, nested := range msg.Messages {
		generateMessage(g, nested)
	}
}

// generateEnum defines a Go-native enum type that mirrors a protobuf enum's
// values, entirely decoupled from the real protoc-gen-go-generated enum
// type. It instead follows Go's iota syntax.
func generateEnum(g *protogen.GeneratedFile, enum *protogen.Enum, filePrefix string) {
	typeName := enum.GoIdent.GoName
	g.P("type ", typeName, " uint32")
	g.P()
	g.P("const (")
	for i, v := range enum.Values {
		if int(v.Desc.Number()) != i {
			panic(fmt.Sprintf("enum %s value %s has number %d, want %d: iota-based generation requires sequential enum values", typeName, v.Desc.Name(), v.Desc.Number(), i))
		}
		valuePath := filePrefix + "/" + typeName + "/" + string(v.Desc.Name())
		g.P(preprocess.DirectivePrivate, " ", valuePath)
		if i == 0 {
			g.P(enumValueConstName(enum, v), " ", typeName, " = iota")
		} else {
			g.P(enumValueConstName(enum, v))
		}
	}
	g.P(")")
	g.P()
}

// isHiddenMessage reports whether a message's fully-qualified proto name
// matches any glob pattern in hiddenMessages.
func isHiddenMessage(fullName string) bool {
	for _, pattern := range hiddenMessages {
		matched, err := path.Match(pattern, fullName)
		if err != nil {
			panic(fmt.Sprintf("invalid hiddenMessages glob pattern %q: %v", pattern, err))
		}
		if matched {
			return true
		}
	}
	return false
}

// enumValueConstName computes a stripped, idiomatic Go constant name for an
// enum value.
func enumValueConstName(enum *protogen.Enum, v *protogen.EnumValue) string {
	localPrefix := screamingSnake(string(enum.Desc.Name())) + "_"
	valName := string(v.Desc.Name())
	if !strings.HasPrefix(valName, localPrefix) {
		return v.GoIdent.GoName
	}
	suffix := strings.TrimPrefix(valName, localPrefix)
	if suffix == "" {
		return v.GoIdent.GoName
	}
	return enum.GoIdent.GoName + camelCaseSnake(suffix)
}

// unexportedName converts an exported name to an unexported name by
// lowercasing the first character.
func unexportedName(name string) string {
	if name == "" {
		return name
	}
	r := []rune(name)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}
